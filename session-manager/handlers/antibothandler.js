import config from '../config.js';
import brand from '../../shared/brand.js';
import logger from '../../shared/logger.js';
import { AIRich } from '../lib/NIXCODE.js';
import { SessionConfig } from '../database/index.js';

const log = logger.child('antibot');

const SYM = brand.SYM;

const metadataCache = new Map();
const METADATA_TTL  = 60000;

const WARN_TTL_MS   = 24 * 60 * 60 * 1000;
const MAX_WARNINGS  = 3;
const MAX_TRACK     = 5000;

const warnings = new Map();

const SIGNATURE_PATTERNS = [
  /this message was sent by a bot/i,
  /powered by.*(?:ai|gpt|bot)/i,
  /i am (?:a|an) (?:bot|ai|assistant)/i,
  /automated (?:message|reply|response)/i,
  /automatic (?:message|reply|response)/i,
  /sent (?:via|using).{0,20}bot/i,
  /generated by ai/i
];

const OTHER_PREFIX_REGEX = /^[./#$%&+\-~!]([a-zA-Z0-9_]{2,25})(?:\s|$)/;

const COMMON_BOT_COMMANDS = [
  'menu', 'help', 'start', 'ping', 'alive', 'owner', 'panel',
  'list', 'buy', 'sell', 'topup', 'saldo', 'balance',
  'register', 'login', 'profile', 'settings', 'config',
  'join', 'leave', 'group', 'promote', 'demote', 'kick',
  'sticker', 'img', 'image', 'video', 'audio', 'music', 'play',
  'ai', 'gpt', 'chatgpt', 'gemini', 'claude', 'deepseek',
  'download', 'dl', 'yt', 'youtube', 'tiktok', 'insta', 'ig', 'fb',
  'weather', 'news', 'wiki', 'google', 'search', 'lyrics',
  'status', 'story', 'uptime', 'runtime', 'version', 'speed',
  'donate', 'support', 'contact', 'rules',
  'antilink', 'antispam', 'antibot', 'antidelete', 'antitag',
  'mode', 'self', 'public', 'private', 'broadcast',
  'setbio', 'setname', 'setpp', 'block', 'unblock',
  'fact', 'joke', 'meme', 'truth', 'dare',
  'roast', 'insult', 'marry', 'hug', 'kiss', 'slap',
  'script', 'sc', 'scbot', 'botsource'
];

function warnKey(chatId, senderNumber) {
  return `${chatId}:${senderNumber}`;
}

function getWarnings(chatId, senderNumber) {
  const key = warnKey(chatId, senderNumber);
  const entry = warnings.get(key);

  if (!entry) return 0;

  if (Date.now() - entry.at > WARN_TTL_MS) {
    warnings.delete(key);
    return 0;
  }

  return entry.count;
}

function addWarning(chatId, senderNumber) {
  const key = warnKey(chatId, senderNumber);
  const existing = warnings.get(key);

  const count = (existing && Date.now() - existing.at < WARN_TTL_MS)
    ? existing.count + 1
    : 1;

  warnings.set(key, { count, at: Date.now() });

  if (warnings.size > MAX_TRACK) {
    const first = warnings.keys().next().value;
    warnings.delete(first);
  }

  return count;
}

function clearWarnings(chatId, senderNumber) {
  warnings.delete(warnKey(chatId, senderNumber));
}

async function getGroupMetadata(sock, chatId) {
  const cached = metadataCache.get(chatId);
  if (cached && Date.now() - cached.at < METADATA_TTL) return cached.data;

  try {
    const data = await sock.groupMetadata(chatId);
    metadataCache.set(chatId, { data, at: Date.now() });
    return data;
  } catch (err) {
    log.warn(`groupMetadata failed: ${err.message}`);
    return null;
  }
}

function invalidateMetadata(chatId) {
  metadataCache.delete(chatId);
}

function getSenderJid(msg) {
  return msg.key?.participant || msg.key?.remoteJid || '';
}

function getSenderNumber(msg) {
  const jid = getSenderJid(msg);
  if (!jid) return '';
  return jid.split('@')[0].split(':')[0].replace(/\D/g, '');
}

function getTextBody(msg) {
  const m = msg.message;
  if (!m) return '';
  return (
    m.conversation ||
    m.extendedTextMessage?.text ||
    m.imageMessage?.caption ||
    m.videoMessage?.caption ||
    m.documentMessage?.caption ||
    ''
  );
}

function isSuperOwner(number) {
  const clean = String(number || '').replace(/\D/g, '');
  if (!clean) return false;

  const main = String(config.owners.whatsapp.id || '').replace(/\D/g, '');
  if (main && clean === main) return true;

  return (config.owners.whatsapp.co || []).some(
    (co) => String(co.id || '').replace(/\D/g, '') === clean
  );
}

function isAdminInGroup(metadata, jid) {
  if (!metadata?.participants) return false;
  const me = metadata.participants.find((p) => p.id === jid);
  if (!me) return false;
  return me.admin === 'admin' || me.admin === 'superadmin';
}

function isBotJid(jid) {
  return String(jid || '').endsWith('@bot');
}

function hasBotMetadata(msg) {
  const m = msg.message;
  if (!m) return false;

  if (m.messageContextInfo?.botMetadata) return true;

  const contexts = [
    m.extendedTextMessage?.contextInfo,
    m.imageMessage?.contextInfo,
    m.videoMessage?.contextInfo,
    m.audioMessage?.contextInfo,
    m.documentMessage?.contextInfo,
    m.stickerMessage?.contextInfo
  ].filter(Boolean);

  for (const ctx of contexts) {
    if (ctx.forwardedAiBotMessageInfo) return true;
    if (ctx.forwardOrigin === 4) return true;
  }

  return false;
}

function isInteractiveMessage(msg) {
  const m = msg.message;
  if (!m) return false;

  return !!(
    m.interactiveMessage ||
    m.buttonsMessage ||
    m.listMessage ||
    m.templateMessage ||
    m.templateButtonReplyMessage ||
    m.buttonsResponseMessage ||
    m.listResponseMessage ||
    m.interactiveResponseMessage ||
    m.pollCreationMessage ||
    m.pollCreationMessageV2 ||
    m.pollCreationMessageV3
  );
}

function isInBlacklist(senderNumber, cfg) {
  const list = Array.isArray(cfg.antibotBlacklist) ? cfg.antibotBlacklist : [];
  if (!list.length) return false;

  const clean = String(senderNumber || '').replace(/\D/g, '');
  if (!clean) return false;

  return list.some((n) => String(n).replace(/\D/g, '') === clean);
}

function hasSignatureText(text, cfg) {
  if (!cfg.antibotStrict) return false;

  const t = String(text || '');
  if (!t) return false;

  return SIGNATURE_PATTERNS.some((rx) => rx.test(t));
}

function isOtherBotCommand(text, ownPrefix) {
  const t = String(text || '').trim();
  if (!t) return null;

  if (ownPrefix && t.startsWith(ownPrefix)) return null;

  const match = t.match(OTHER_PREFIX_REGEX);
  if (!match) return null;

  const prefix = t[0];
  const word   = match[1].toLowerCase();

  if (!COMMON_BOT_COMMANDS.includes(word)) return null;

  return { prefix, command: word };
}

function detectBot(msg, senderNumber, cfg, senderJid, ownPrefix) {
  if (isBotJid(senderJid)) {
    return { reason: 'meta ai bot' };
  }

  if (hasBotMetadata(msg)) {
    return { reason: 'ai bot metadata' };
  }

  if (isInteractiveMessage(msg)) {
    return { reason: 'interactive bot output' };
  }

  if (isInBlacklist(senderNumber, cfg)) {
    return { reason: 'blacklisted bot number' };
  }

  const text = getTextBody(msg);

  if (cfg.antibotDetectCommands) {
    const otherBot = isOtherBotCommand(text, ownPrefix);
    if (otherBot) {
      return {
        reason: `other bot command · ${otherBot.prefix}${otherBot.command}`
      };
    }
  }

  if (hasSignatureText(text, cfg)) {
    return { reason: 'bot signature' };
  }

  return null;
}

async function deleteMessage(sock, chatId, msg) {
  try {
    await sock.sendMessage(chatId, { delete: msg.key });
  } catch (err) {
    log.warn(`delete failed: ${err.message}`);
  }
}

async function sendWarn(sock, chatId, senderJid, senderNumber, reason, strike, max) {
  try {
    const rich = new AIRich(sock).setTitle(brand.BOT_NAME);

    rich.addText(
      `${SYM.timer} *Antibot Warning*\n\n` +
      `${SYM.arrow} @${senderNumber}\n` +
      `${SYM.arrow} strike · ${strike}/${max}\n` +
      `${SYM.arrow} reason · ${reason}\n\n` +
      `${SYM.info} ${
        strike >= max
          ? 'final warning — next violation will remove you'
          : `${max - strike} more warning${max - strike === 1 ? '' : 's'} before removal`
      }`,
      { id: 'warn' }
    );

    rich.addText(`[View channel](${config.bot.channelLink || config.links.whatsappChannel})`);
    rich.setFooter(config.msg.footer);

    await rich.send(chatId, { mentions: [senderJid] });
  } catch (err) {
    log.warn(`warn send failed: ${err.message}`);
  }
}

async function sendKickNotice(sock, chatId, senderJid, senderNumber, reason, strike, max) {
  try {
    const rich = new AIRich(sock).setTitle(brand.BOT_NAME);

    rich.addText(
      `${SYM.cross} *User Removed*\n\n` +
      `${SYM.arrow} @${senderNumber}\n` +
      `${SYM.arrow} strike · ${strike}/${max}\n` +
      `${SYM.arrow} reason · ${reason}\n\n` +
      `${SYM.info} max warnings reached — user removed from group`,
      { id: 'kick' }
    );

    rich.addText(`[View channel](${config.bot.channelLink || config.links.whatsappChannel})`);
    rich.setFooter(config.msg.footer);

    await rich.send(chatId, { mentions: [senderJid] });
  } catch (err) {
    log.warn(`kick notice failed: ${err.message}`);
  }
}

async function kickUser(sock, chatId, senderJid) {
  if (isBotJid(senderJid)) {
    log.debug(`cannot kick @bot JID: ${senderJid}`);
    return false;
  }

  try {
    await sock.groupParticipantsUpdate(chatId, [senderJid], 'remove');
    invalidateMetadata(chatId);
    return true;
  } catch (err) {
    log.warn(`kick failed: ${err.message}`);
    return false;
  }
}

async function handleAntibot(sock, sessionId, msg) {
  const chatId = msg.key?.remoteJid || '';

  if (!chatId.endsWith('@g.us')) return;
  if (msg.key?.fromMe) return;
  if (!msg.message) return;

  const cfg = await SessionConfig.findBySessionId(sessionId);
  if (!cfg) return;

  const mode = cfg.antibotMode || (cfg.antibot ? 'mute' : 'off');
  if (mode === 'off') return;

  const senderJid    = getSenderJid(msg);
  const senderNumber = getSenderNumber(msg);
  if (!senderJid) return;

  if (!isBotJid(senderJid) && !senderNumber) return;

  if (senderNumber && isSuperOwner(senderNumber)) return;

  const metadata = await getGroupMetadata(sock, chatId);
  if (metadata && isAdminInGroup(metadata, senderJid)) return;

  const ownPrefix = cfg.prefix || config.prefixes.whatsappDefault;

  const detected = detectBot(msg, senderNumber, cfg, senderJid, ownPrefix);
  if (!detected) return;

  log.event('antibot.triggered', {
    sessionId,
    chatId,
    sender: senderNumber || senderJid,
    reason: detected.reason,
    mode
  });

  await deleteMessage(sock, chatId, msg);

  if (mode === 'mute' || mode === 'delete') {
    // silent delete — no warning, no kick

  } else if (mode === 'warn') {
    const strike = addWarning(chatId, senderNumber);
    await sendWarn(sock, chatId, senderJid, senderNumber || 'bot', detected.reason, strike, 999);

  } else if (mode === 'kick') {
    const strike = addWarning(chatId, senderNumber);

    if (strike < MAX_WARNINGS) {
      await sendWarn(sock, chatId, senderJid, senderNumber || 'bot', detected.reason, strike, MAX_WARNINGS);
    } else {
      await sendKickNotice(sock, chatId, senderJid, senderNumber || 'bot', detected.reason, strike, MAX_WARNINGS);
      const kicked = await kickUser(sock, chatId, senderJid);
      if (kicked) {
        clearWarnings(chatId, senderNumber);
      }
    }
  }

  try {
    await SessionConfig.updateOne(
      { sessionId },
      { $inc: { 'stats.antibotTriggers': 1 } }
    );
  } catch {}
}

function attachAntibotHandler(sock, sessionId) {
  sock.ev.on('messages.upsert', async ({ messages, type }) => {
    if (type !== 'notify') return;

    for (const msg of messages) {
      try {
        await handleAntibot(sock, sessionId, msg);
      } catch (err) {
        log.error(`antibot crashed for ${sessionId}: ${err.message}`);
      }
    }
  });

  log.debug(`Antibot handler attached to ${sessionId}`);
}

function cleanup() {
  metadataCache.clear();
  warnings.clear();
}

